/**
 * Simulates pagination for demo catalog
 */
export function getMockPagedMovies(page = 1, pageSize = 12) {
  const startIndex = (page - 1) * pageSize;
  const endIndex = startIndex + pageSize;
  const results = MOCK_MOVIES.slice(startIndex, endIndex);
  const totalPages = Math.ceil(MOCK_MOVIES.length / pageSize);

  return {
    page,
    results,
    total_pages: totalPages,
    total_results: MOCK_MOVIES.length,
  };
}

/**
 * Simulates text search across mock catalog
 */
export function searchMockMovies(query, page = 1, pageSize = 12) {
  if (!query || !query.trim()) {
    return getMockPagedMovies(page, pageSize);
  }

  const cleanQuery = query.toLowerCase().trim();
  const matched = MOCK_MOVIES.filter((movie) => 
    movie.title.toLowerCase().includes(cleanQuery) ||
    movie.overview.toLowerCase().includes(cleanQuery)
  );

  const startIndex = (page - 1) * pageSize;
  const endIndex = startIndex + pageSize;
  const results = matched.slice(startIndex, endIndex);
  const totalPages = Math.max(1, Math.ceil(matched.length / pageSize));

  return {
    page,
    results,
    total_pages: totalPages,
    total_results: matched.length,
  };
}
